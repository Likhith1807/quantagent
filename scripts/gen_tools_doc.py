"""Regenerate docs/TOOLS.md from the live server: real schemas and real outputs on the
current database. Run after ingest (and train for predict_volatility):  python scripts/gen_tools_doc.py"""
import asyncio
import json
from pathlib import Path

import pandas as pd
from mcp import Client

from quantagent.server import build_server
from quantagent.tools._base import get_services

ROOT = Path(__file__).resolve().parents[1]



def examples(repo) -> tuple[dict, list]:
    """Example calls on real funds picked from the loaded database (longest NAV histories)."""
    cov = repo.nav_coverage()
    schemes = {r["scheme_code"]: r for r in repo.all_schemes()}
    by_len = sorted(cov, key=lambda c: (-cov[c]["n_points"], c))
    large = [c for c in by_len if schemes[c]["sub_category"] == "Large Cap"] or by_len
    a, b, c = large[0], large[1], by_len[0] if by_len[0] not in large[:2] else by_len[3]
    word = schemes[a]["scheme_name"].split()[0]
    ex = {
        "search_funds": {"query": word, "limit": 3},
        "get_nav_history": {"scheme_code": a, "frequency": "monthly",
                            "start_date": str((pd.Timestamp(repo.meta["data_as_of"]) - pd.DateOffset(months=6)).date())},
        "compare_funds": {"scheme_codes": [a, b, c], "period": "3y"},
        "rank_funds": {"metric": "sharpe", "period": "3y", "category": "Large Cap", "top_n": 3},
        "get_risk_metrics": {"scheme_code": a, "period": "3y"},
        "get_benchmark_comparison": {"scheme_code": a, "period": "3y"},
        "check_data_quality": {"scheme_codes": [a, b]},
        "get_data_provenance": {"scheme_code": a},
        "predict_volatility": {"scheme_code": a},
    }
    errors = [("get_risk_metrics", {"scheme_code": a, "start_date": str(pd.Timestamp(repo.meta["data_as_of"]).date())}),
              ("search_funds", {"query": "x'; DROP TABLE schemes;--"})]
    return ex, errors


def trim(obj, depth=0):
    """Keep examples readable: shorten long lists."""
    if isinstance(obj, dict):
        return {k: trim(v, depth + 1) for k, v in obj.items()}
    if isinstance(obj, list):
        items = [trim(v, depth + 1) for v in obj[:4]]
        return items + ([f"... {len(obj) - 4} more"] if len(obj) > 4 else [])
    if isinstance(obj, float):
        return round(obj, 6)
    return obj


def args_table(schema: dict) -> str:
    rows = ["| Argument | Type | Default | Notes |", "|---|---|---|---|"]
    req = set(schema.get("required", []))
    for name, p in schema.get("properties", {}).items():
        types = [x for x in p.get("anyOf", [p])]
        t = " \\| ".join(
            "enum: " + ", ".join(map(str, x["enum"])) if "enum" in x else
            (f"{x.get('type')}[{x['items'].get('type', '')}]" if x.get("type") == "array" else str(x.get("type")))
            for x in types if x.get("type") != "null")
        bits = []
        for x in types:
            for k in ("pattern", "minimum", "maximum", "minLength", "maxLength", "minItems", "maxItems", "format"):
                if k in x:
                    bits.append(f"{k}={x[k]}")
        desc = p.get("description", "")
        default = "required" if name in req else json.dumps(p.get("default"))
        rows.append(f"| `{name}` | {t} | {default} | {desc} {'; '.join(bits)} |".replace("\n", " "))
    return "\n".join(rows)


async def main() -> None:
    repo = get_services().repo
    ex, errors = examples(repo)
    out = [
        "# QuantAgent MCP tools",
        "",
        "Generated by `scripts/gen_tools_doc.py` from the running server and the current database",
        f"(data_nature **{repo.meta['data_nature']}**, data as of {repo.meta['data_as_of']}, version "
        f"{repo.meta['data_version']}). Example funds are picked automatically (longest NAV histories). Errors,",
        "including a benchmark tool call without TRI data loaded, are shown as returned.",
        "",
        "## Running",
        "",
        "```bash",
        "pip install -e .[dev]",
        "quantagent setup                          # download AMFI data, ingest -> data/db/quantagent.db",
        "npx @modelcontextprotocol/inspector quantagent-server   # browse and call the tools",
        "quantagent-server --transport streamable-http --port 8000",
        "docker build -t quantagent . && docker run -i --rm -v qa:/app/var quantagent serve",
        "```",
        "",
        "Claude Desktop (`claude_desktop_config.json`):",
        "",
        "```json",
        json.dumps({"mcpServers": {"quantagent": {
            "command": "C:/path/to/quantagent/.venv/Scripts/quantagent-server.exe",
            "env": {"QUANTAGENT_DB_URL": "sqlite:///C:/path/to/quantagent/data/db/quantagent.db",
                    "QUANTAGENT_MODEL_DIR": "C:/path/to/quantagent/models/registry"}}}},
            indent=2),
        "```",
        "",
        "## Conventions",
        "",
        "* Returns, volatility, drawdowns and rates are fractions (`0.12` = 12%); expense ratios are percent.",
        "* Every result has `meta` (period, n_obs, data_as_of, data_version, calc_version, data_nature,",
        "  assumptions, request_id), `warnings` and `excluded`.",
        "* Failures return `is_error: true` with JSON `{code, message, details}`. Codes: `INVALID_INPUT`,",
        "  `NOT_FOUND`, `INSUFFICIENT_HISTORY`, `NO_OVERLAP`, `DATA_QUALITY`, `MODEL_UNAVAILABLE`, `INTERNAL`",
        "  (INTERNAL details carry a",
        "  `request_id` that matches the server's stderr log).",
        "* Unknown argument names are rejected. No argument accepts SQL, column names or expressions.",
        "",
    ]
    async with Client(build_server()) as c:
        tools = {t.name: t for t in (await c.list_tools()).tools}
        for name, args in ex.items():
            t = tools[name]
            res = await c.call_tool(name, args)
            body = json.loads(res.content[0].text) if res.is_error else trim(res.structured_content)
            out += [f"## `{name}`", "", t.description.strip(), "", args_table(t.input_schema), "",
                    "Example call:", "", "```json", json.dumps(args), "```", "",
                    "Error returned:" if res.is_error else "Result (lists shortened):", "",
                    "```json", json.dumps(body, indent=1, default=str), "```", ""]
        out += ["## Error examples", ""]
        for name, args in errors:
            res = await c.call_tool(name, args)
            out += [f"`{name}` with `{json.dumps(args)}`:", "", "```json",
                    json.dumps(json.loads(res.content[0].text), indent=1), "```", ""]
        resources = (await c.list_resources()).resources
        prompts = (await c.list_prompts()).prompts
        out += ["## Resources and prompt", ""]
        out += [f"* `{r.uri}`: {r.description}" for r in resources]
        out += [f"* prompt `{p.name}`(question): {p.description}" for p in prompts]
    (ROOT / "docs" / "TOOLS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("wrote docs/TOOLS.md")


if __name__ == "__main__":
    asyncio.run(main())
