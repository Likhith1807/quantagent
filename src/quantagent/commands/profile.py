"""Write docs/DATA_PROFILE.md from the built database: every source with its download date,
coverage and licence (from the data_sources table), the universe, quality results and biases.

Usage: quantagent profile [--out docs/DATA_PROFILE.md]
"""
import argparse
import json
from pathlib import Path

import pandas as pd

from ..config import get_settings
from ..data.engine import make_readonly_engine
from ..data.repository import Repository


def _cov(v) -> str:
    if not v:
        return "-"
    d = json.loads(v) if isinstance(v, str) else v
    if isinstance(d, dict):
        return "<br>".join(f"{k}: {x}" for k, x in d.items())
    return str(d)


def render(repo: Repository) -> str:
    m = repo.meta
    cov = pd.DataFrame(repo.nav_coverage().values())
    schemes = pd.DataFrame(repo.all_schemes())
    years = (pd.to_datetime(cov["end"]) - pd.to_datetime(cov["start"])).dt.days / 365.25
    ingest = {r["table_name"]: r for r in repo.last_ingest()}
    nav_log = json.loads(ingest["nav_history"]["coverage"])
    counts = repo.table_counts()
    lines = [
        "# Data profile", "",
        f"Generated by `quantagent profile` from the database: data_nature **{m['data_nature']}**, data version "
        f"{m['data_version']}, data as of {m['data_as_of']}, built {m.get('built_at')}. Re-run it after every "
        "ingest; nothing here is typed by hand.", "",
        "## Sources", "",
        "| File | Source | URL | Retrieved (UTC) | Licence | Coverage | SHA-256 |", "|---|---|---|---|---|---|---|"]
    for s in repo.data_sources():
        if s["data_nature"] == "reference":
            continue
        lines.append(f"| {s.get('file') or '-'} | {s['source']} | {s['url'] or '-'} | {s['retrieved_at'] or '-'} | "
                     f"{s['licence'] or '-'} | {_cov(s.get('coverage'))} | `{(s['sha256'] or '')[:12]}` |")
    refs = [s for s in repo.data_sources() if s["data_nature"] == "reference"]
    lines += ["", "Reference files committed to the repository (MIT): " +
              ", ".join(f"`{s['source']}`" for s in refs) + ".", ""]
    missing = []
    if counts.get("benchmarks", 0) == 0:
        missing.append("**Benchmarks: not loaded.** Download Nifty TRI CSVs from niftyindices.com into "
                       "`data/external/niftyindices/` and run `quantagent load-manual` then `quantagent ingest`. "
                       "Until then benchmark tools return NOT_FOUND and alpha/beta are missing.")
    if counts.get("risk_free_rates", 0) == 0:
        missing.append("**Risk-free series: not loaded.** The configured constant is used and every response "
                       "labels it as an assumption. Put 91-day T-bill yields in `data/external/tbill_91d.csv`.")
    if missing:
        lines += ["## Not loaded", ""] + [f"* {x}" for x in missing] + [""]
    by_cat = schemes.groupby("sub_category").size().sort_values(ascending=False)
    lines += [
        "## Universe", "",
        f"{len(schemes)} schemes ({', '.join(f'{k}: {v}' for k, v in schemes['plan_type'].value_counts().items())}"
        f"; options: {', '.join(f'{k}: {v}' for k, v in schemes['option_type'].value_counts().items())}). "
        f"{counts['nav_history']:,} NAV rows from {cov['start'].min()} to {cov['end'].max()}. History per scheme: "
        f"median {years.median():.1f} years, min {years.min():.1f}, max {years.max():.1f}.", "",
        "| SEBI category | Schemes |", "|---|---|", *[f"| {k} | {v} |" for k, v in by_cat.items()], "",
        "## Quality", "",
        f"Ingest quality status per scheme: {nav_log['quality_status']}. Rows rejected at ingest: "
        f"{sum(r['rows_rejected'] for r in ingest.values())} (reasons in `reports/rejected_rows.csv`).", "",
        f"Trading calendar: {m.get('calendar_source')}.", "",
        "## Assumptions recorded at ingest", "", *[f"* {a}" for a in m["assumptions"]], "",
        "## Known biases", "", *[f"* {b}" for b in m["known_biases"]], "",
        "## Findings", "", *[f"* {f}" for f in m["dataset_findings"]], ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> None:
    s = get_settings()
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path, default=Path("docs") / "DATA_PROFILE.md")
    a = ap.parse_args(argv)
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(render(Repository(make_readonly_engine(s.db_url, 60))), encoding="utf-8")
    print(f"wrote {a.out}")
