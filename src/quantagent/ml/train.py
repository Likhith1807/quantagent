"""End-to-end training run: panel -> walk-forward -> evaluation -> final fit -> registry + reports."""
import json
import random
import uuid
from dataclasses import asdict
from datetime import UTC, datetime
from pathlib import Path

import numpy as np
import pandas as pd
import sklearn

from ..data.repository import Repository
from . import registry
from .volatility import FEATURES, panel
from .walkforward import (
    BASELINES,
    MODELS,
    TRAIN_EVERY,
    Config,
    evaluate,
    holdout_start,
    make_model,
    walk_forward,
)


def load_navs(repo: Repository, max_schemes: int | None = None) -> dict[str, pd.Series]:
    """Growth/NA NAV series for every scheme (IDCW NAVs drop on payouts, so they are excluded)."""
    codes = sorted(s["scheme_code"] for s in repo.all_schemes() if s["option_type"] != "IDCW")
    if max_schemes:
        codes = codes[:max_schemes]
    return {c: repo.nav_series(c, None, None) for c in codes}


def run(repo: Repository, cfg: Config, registry_root: Path, report_path: Path, experiments_path: Path,
        repo_root: Path, max_schemes: int | None = None, log=print) -> dict:
    random.seed(cfg.seed)
    np.random.seed(cfg.seed)
    meta = repo.meta
    navs = load_navs(repo, max_schemes)
    p = panel(navs, cfg.horizon)
    log(f"panel: {len(p)} origins over {p['scheme_code'].nunique()} schemes")
    preds, folds = walk_forward(p, navs, cfg, log)
    if preds.empty:
        raise RuntimeError("walk-forward produced no test rows; not enough history")
    compared = [*[b for b in BASELINES if cfg.garch or b != "garch"], *MODELS]
    res = evaluate(preds, compared, holdout_start(p, cfg))
    res["folds"] = folds
    best = res["selected"]["model"]

    full = p[p["clean"].astype(bool)].dropna(subset=[*FEATURES, "y"])
    full = full[full["n_hist"] % TRAIN_EVERY == 0]
    final, har = make_model(best, cfg).fit(full), make_model("har", cfg).fit(full)
    created = datetime.now(UTC)
    version = f"vol{cfg.horizon}-{best}-{created:%Y%m%d%H%M%S}"
    config = {"model_kind": best, "features": FEATURES, "horizon": cfg.horizon, "target":
              "annualised realised volatility of the next 21 daily log NAV returns",
              "walk_forward": asdict(cfg), "train_rows": len(full),
              "train_range": [str(full["date"].min().date()), str(full["target_end"].max().date())],
              "data_nature": meta.get("data_nature"), "data_version": meta["data_version"],
              "data_as_of": meta["data_as_of"], "data_source": meta.get("data_source"),
              "git_commit": registry.git_commit(repo_root), "sklearn": sklearn.__version__}
    registry.save(registry_root, version, {"model": final, "har": har}, config, res)

    experiments_path.parent.mkdir(parents=True, exist_ok=True)
    with experiments_path.open("a", encoding="utf-8") as f:
        f.write(json.dumps({"run_id": str(uuid.uuid4()), "at": created.isoformat(timespec="seconds"),
                            "version": version, **{k: config[k] for k in ("data_nature", "data_version",
                                                                         "data_as_of", "git_commit")},
                            "config": asdict(cfg), "max_schemes": max_schemes,
                            "models": res["models"], "selected": res["selected"]}, default=str) + "\n")
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(render_report(res, config, version), encoding="utf-8")
    return {"version": version, **res}


NAMES = {"naive": "Naive (last 22-day RV)", "ewma": "EWMA (RiskMetrics, lambda 0.94)",
         "har": "HAR-RV (log, pooled OLS)", "garch": "GARCH(1,1) per scheme",
         "ridge": "Ridge (log features)", "gbm": "Gradient boosting (log features)"}


def render_report(res: dict, config: dict, version: str) -> str:
    sel, t = res["selected"], res["test"]
    best = NAMES[sel["model"]]
    f, d = res["test_filtered_at_origin"], res["test_clean_target_ex_post"]
    lines = [
        "# Volatility model: walk-forward results", "",
        f"Model version `{version}`; data_nature **{config['data_nature']}**, data version "
        f"{config['data_version']}, data as of {config['data_as_of']}. Generated by `quantagent train`.", "",
        f"Target: {config['target']}. Folds are calendar years; every model is refitted per fold on training "
        f"rows whose target window ends at least {config['walk_forward']['gap_days']} days before the fold "
        "starts (purge + embargo).", "",
        "Protocol:", "",
        f"* **Selection period** ({res['selection']['period'][0]} to {res['selection']['period'][1]}, "
        f"{res['selection']['n_test']} rows, {res['selection']['n_months']} months): the served model is the one "
        "of HAR-RV, ridge and boosting with the lowest mean QLIKE here.",
        f"* **Test period** ({t['period'][0]} to {t['period'][1]}, {t['n_test']} rows, {t['n_months']} months, "
        f"from {sel['holdout_start']}): not used for any choice. All scores below are from this period.",
        "* Regression models are fitted on log volatility and converted back with Duan's smearing factor "
        "(the mean of exp(residual) on the training rows), which corrects the downward bias of exp(E[log vol]).",
        "* Training rows whose target window contains a suspect NAV (a daily move above 15%, or 5+ identical "
        "NAVs: the check_data_quality rules) are dropped. Those targets are in the past at fit time, so this "
        "uses no future information.", "",
        "## Test period, all rows (headline)", "", *_table(t, sel["model"]), "",
        f"Lower is better. QLIKE is the Patton (2011) loss on variance; MAE is on annualised volatility. The DM "
        f"columns test **{best} (the served model) against the model in that row**: Diebold-Mariano on the monthly "
        "mean QLIKE differential, Newey-West lag 1, HLN correction. A negative statistic means the served model "
        "has the lower loss.", "",
        "## Test period, filtered at the forecast origin", "",
        f"Drops {f['excluded']} test rows whose scheme had a suspect NAV in the 252 trading days up to the origin. "
        "This is known when the forecast is made, so a live system could apply the same rule.", "",
        *(_table(f, sel["model"]) if f["excluded"] else ["No test row is affected; the scores equal the headline."]),
        "",
        "## Diagnostic only: test rows with a clean target window", "",
        f"Drops {d['excluded']} test rows whose *target* window contains a suspect NAV. That uses information "
        "from after the origin, so it is not a valid test result; it shows how much of the loss comes from a "
        "few NAV errors.", "",
        *(_table(d, sel["model"]) if d["excluded"] else ["No test row is affected; the scores equal the headline."]),
        "",
        "## Selection period", "", *_table(res["selection"], None), "",
        f"Served model: **{best}**, chosen on the selection period. On the test period its QLIKE is "
        f"{sel['qlike_vs_ewma_pct']:+.1f}% vs EWMA and {sel['qlike_vs_best_other_pct']:+.1f}% vs the best other "
        f"baseline ({NAMES[sel['best_other_baseline']]}). ML (ridge or boosting) beat HAR-RV on the selection "
        f"period: **{'yes' if sel['ml_beats_har'] else 'no'}**; on the test period: "
        f"**{'yes' if sel['ml_beats_har_test'] else 'no'}**.", "",
        "## Folds", "", "| Test start | Test end | Period | Train rows | Last train target | Test rows | Schemes |",
        "|---|---|---|---|---|---|---|"]
    for fo in res["folds"]:
        period = "test" if fo["test_start"] >= sel["holdout_start"] else "selection"
        lines.append(f"| {fo['test_start']} | {fo['test_end']} | {period} | {fo['train_rows']} | "
                     f"{fo['train_last_target_end']} | {fo['test_rows']} | {fo['schemes']} |")
    return "\n".join(lines) + "\n"


def _table(res: dict, ref: str | None) -> list[str]:
    if ref is None:
        out = ["| Model | QLIKE | QLIKE median | MAE (vol) |", "|---|---|---|---|"]
        return out + [f"| {NAMES.get(m, m)} | {v['qlike']:.4f} | {v['qlike_median']:.4f} | {v['mae']:.4f} |"
                      for m, v in res["models"].items()]
    out = [f"| Model | QLIKE | QLIKE median | MAE (vol) | DM stat, {ref} vs row | p-value | months {ref} better |",
           "|---|---|---|---|---|---|---|"]
    for mdl, v in res["models"].items():
        dm = res["dm"].get(f"{ref}_vs_{mdl}")
        name = f"**{NAMES.get(mdl, mdl)} (served)**" if mdl == ref else NAMES.get(mdl, mdl)
        out.append(f"| {name} | {v['qlike']:.4f} | {v['qlike_median']:.4f} | {v['mae']:.4f} | "
                   + (f"{dm['stat']:.2f} | {dm['p_value']:.3g} | {dm['months_better_pct']:.0f}% |" if dm
                      else "- | - | - |"))
    return out
