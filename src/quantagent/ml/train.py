"""End-to-end training run: panel -> walk-forward -> evaluation -> final fit -> registry + reports."""
import json
import random
import uuid
from dataclasses import asdict
from datetime import UTC, datetime
from pathlib import Path

import numpy as np
import pandas as pd
import sklearn

from ..data.repository import Repository
from . import registry
from .volatility import FEATURES, panel
from .walkforward import BASELINES, MODELS, TRAIN_EVERY, Config, evaluate, make_model, walk_forward


def load_navs(repo: Repository, max_schemes: int | None = None) -> dict[str, pd.Series]:
    """Growth/NA NAV series for every scheme (IDCW NAVs drop on payouts, so they are excluded)."""
    codes = sorted(s["scheme_code"] for s in repo.all_schemes() if s["option_type"] != "IDCW")
    if max_schemes:
        codes = codes[:max_schemes]
    return {c: repo.nav_series(c, None, None) for c in codes}


def run(repo: Repository, cfg: Config, registry_root: Path, report_path: Path, experiments_path: Path,
        repo_root: Path, max_schemes: int | None = None, log=print) -> dict:
    random.seed(cfg.seed)
    np.random.seed(cfg.seed)
    meta = repo.meta
    navs = load_navs(repo, max_schemes)
    p = panel(navs, cfg.horizon)
    log(f"panel: {len(p)} origins over {p['scheme_code'].nunique()} schemes")
    preds, folds = walk_forward(p, navs, cfg, log)
    if preds.empty:
        raise RuntimeError("walk-forward produced no test rows; not enough history")
    compared = [*[b for b in BASELINES if cfg.garch or b != "garch"], *MODELS]
    res = evaluate(preds, compared)
    res["folds"] = folds

    # Serve whichever regression model scored best out of sample: HAR-RV, ridge or boosting.
    best = min(["har", *MODELS], key=lambda mdl: res["models"][mdl]["qlike"])
    others = {b: res["models"][b]["qlike"] for b in compared if b in BASELINES and b != best}
    best_other = min(others, key=others.get)
    ml_best = min(MODELS, key=lambda mdl: res["models"][mdl]["qlike"])
    res["selected"] = {
        "model": best, "best_other_baseline": best_other,
        "beats_all_baselines": all(res["models"][best]["qlike"] < q for q in others.values()),
        "ml_beats_har": res["models"][ml_best]["qlike"] < res["models"]["har"]["qlike"],
        "qlike_vs_ewma_pct": 100 * (res["models"][best]["qlike"] / res["models"]["ewma"]["qlike"] - 1),
        "qlike_vs_best_other_pct": 100 * (res["models"][best]["qlike"] / others[best_other] - 1)}

    full = p[p["clean"].astype(bool)].dropna(subset=[*FEATURES, "y"])
    full = full[full["n_hist"] % TRAIN_EVERY == 0]
    final, har = make_model(best, cfg).fit(full), make_model("har", cfg).fit(full)
    created = datetime.now(UTC)
    version = f"vol{cfg.horizon}-{best}-{created:%Y%m%d%H%M%S}"
    config = {"model_kind": best, "features": FEATURES, "horizon": cfg.horizon, "target":
              "annualised realised volatility of the next 21 daily log NAV returns",
              "walk_forward": asdict(cfg), "train_rows": len(full),
              "train_range": [str(full["date"].min().date()), str(full["target_end"].max().date())],
              "data_nature": meta.get("data_nature"), "data_version": meta["data_version"],
              "data_as_of": meta["data_as_of"], "data_source": meta.get("data_source"),
              "git_commit": registry.git_commit(repo_root), "sklearn": sklearn.__version__}
    registry.save(registry_root, version, {"model": final, "har": har}, config, res)

    experiments_path.parent.mkdir(parents=True, exist_ok=True)
    with experiments_path.open("a", encoding="utf-8") as f:
        f.write(json.dumps({"run_id": str(uuid.uuid4()), "at": created.isoformat(timespec="seconds"),
                            "version": version, **{k: config[k] for k in ("data_nature", "data_version",
                                                                         "data_as_of", "git_commit")},
                            "config": asdict(cfg), "max_schemes": max_schemes,
                            "models": res["models"], "selected": res["selected"]}, default=str) + "\n")
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(render_report(res, config, version), encoding="utf-8")
    return {"version": version, **res}


def render_report(res: dict, config: dict, version: str) -> str:
    names = {"naive": "Naive (last 22-day RV)", "ewma": "EWMA (RiskMetrics, lambda 0.94)",
             "har": "HAR-RV (log, pooled OLS)", "garch": "GARCH(1,1) per scheme",
             "ridge": "Ridge (log features)", "gbm": "Gradient boosting (log features)"}
    sel = res["selected"]
    lines = [
        "# Volatility model: walk-forward results", "",
        f"Model version `{version}`; data_nature **{config['data_nature']}**, data version "
        f"{config['data_version']}, data as of {config['data_as_of']}. Generated by `scripts/train_vol.py`.", "",
        f"Target: {config['target']}. Test rows: {res['n_test']} over {res['n_months']} months (clean target "
        f"windows); {res['excluded_suspect']} test rows whose target window contains a suspect NAV (a daily move "
        "above 15% or a run of 5+ identical NAVs, the check_data_quality rules) are scored separately below. "
        f"Folds are calendar years; training targets end at least {config['walk_forward']['gap_days']} days before "
        "each test year (purge + embargo).", ""]
    lines += _table(res, names)
    lines += ["", "Lower is better. QLIKE is the Patton (2011) loss on variance (mean, and median per row); MAE "
              "is on annualised volatility. DM: Diebold-Mariano on the monthly mean QLIKE differential (Newey-West "
              "lag 1, HLN correction); negative = lower loss than EWMA.", "",
              "## Diebold-Mariano, model against each baseline (clean rows)", "",
              "| Comparison | DM stat | p-value | mean QLIKE diff | months | months better |",
              "|---|---|---|---|---|---|"]
    for k, v in res["dm"].items():
        lines.append(f"| {k} | {v['stat']:.2f} | {v['p_value']:.3g} | {v['mean_qlike_diff']:.4f} | {v['months']} | "
                     f"{v['months_better_pct']:.0f}% |")
    lines += ["", "## All test rows, including suspect target windows", "", *_table(res["all_rows"], names)]
    lines += ["", "## Selection", "",
              f"Served model: **{names[sel['model']]}** (lowest out-of-sample QLIKE among HAR-RV, ridge and "
              f"boosting). QLIKE vs EWMA: {sel['qlike_vs_ewma_pct']:+.1f}%; vs the best remaining baseline "
              f"({names[sel['best_other_baseline']]}): {sel['qlike_vs_best_other_pct']:+.1f}%. "
              f"The ML models beat HAR-RV: **{'yes' if sel['ml_beats_har'] else 'no'}**.", "",
              "## Folds", "", "| Test start | Test end | Train rows | Last train target | Test rows | Schemes |",
              "|---|---|---|---|---|---|"]
    for f in res["folds"]:
        lines.append(f"| {f['test_start']} | {f['test_end']} | {f['train_rows']} | {f['train_last_target_end']} | "
                     f"{f['test_rows']} | {f['schemes']} |")
    return "\n".join(lines) + "\n"




def _table(res: dict, names: dict) -> list[str]:
    out = ["| Model | QLIKE | QLIKE median | MAE (vol) | DM stat vs EWMA | DM p vs EWMA |",
           "|---|---|---|---|---|---|"]
    for mdl, v in res["models"].items():
        dm = res["dm"].get(f"{mdl}_vs_ewma")
        out.append(f"| {names.get(mdl, mdl)} | {v['qlike']:.4f} | {v['qlike_median']:.4f} | {v['mae']:.4f} | "
                   + (f"{dm['stat']:.2f} | {dm['p_value']:.3g} |" if dm else "- | - |"))
    return out
